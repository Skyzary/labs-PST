# frozen_string_literal: true

require_relative 'game'
require_relative 'statistics'
require_relative 'errors'

module Battleship
  class Menu
    def initialize
      @stats = Statistics.new
    end

    def run
      loop do
        print_main_menu
        print 'Оберіть дію (1-4): '
        choice = gets

        break if choice.nil? # EOF

        case choice.strip
        when '1'
          game = Game.new(@stats)
          game.start
        when '2'
          show_rules
        when '3'
          show_statistics
        when '4', 'exit', 'q'
          puts "\nДякуємо за гру! До зустрічі на морських просторах! 👋\n\n"
          break
        else
          puts "\n⚠️  Невідомий пункт меню. Будь ласка, введіть число від 1 до 4.\n"
        end
      end
    rescue Interrupt
      puts "\n\nДострокове завершення програми. До побачення!"
    end

    private

    def print_main_menu
      puts <<~MENU

        ==================================================
                    ⚓ КОНСОЛЬНА ГРА: МОРСЬКИЙ БІЙ ⚓
        ==================================================
         1. Почати нову гру
         2. Правила гри
         3. Статистика перемог і поразок
         4. Вихід
        --------------------------------------------------
      MENU
    end

    def show_rules
      puts <<~RULES

        ==================================================
                            ПРАВИЛА ГРИ
        ==================================================
        1. Ігрове поле має розмір 10x10. Рядки позначаються
           літерами A-J, стовпчики — числами 1-10.
        2. Склад флоту кожного гравця:
           - 1 чотирипалубний (4 клітинки)
           - 2 трипалубні (3 клітинки)
           - 3 двопалубні (2 клітинки)
           - 4 однопалубні (1 клітинка)
        3. Кораблі не можуть перетинатися або торкатися один
           одного навіть по діагоналі (буферна зона 1 клітинка).
        4. Гравці ходять по черзі. Якщо ви влучили у корабель
           противника, ви отримуєте право на додатковий постріл.
        5. При повному знищенні корабля всі клітинки навколо
           нього автоматично позначаються промахами.
        6. Введення координат: літера та цифра (наприклад, A5, B10, j1).
        7. Перемагає той, хто першим знищить усі 10 кораблів ворога!
        ==================================================
      RULES
      print "Натисніть Enter, щоб повернутися в головне меню..."
      gets
    end

    def show_statistics
      puts "\n#{@stats.summary}"
      print "Натисніть Enter, щоб повернутися в головне меню..."
      gets
    end
  end
end
